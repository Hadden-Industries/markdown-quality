import assert from "node:assert/strict";
import { basename } from "node:path";

export const releaseVersionPattern =
  /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/u;

const documents = [
  "README.md",
  "CONTRIBUTING.md",
  "SECURITY.md",
  "docs/consumer-guide.md",
  "docs/migration-guide.md",
  "docs/support-and-release.md",
  "docs/ci-trust.md",
  "docs/centralized-contracts.md",
  "docs/json-quality.md",
  "docs/release-operations.md",
];
const metadataPath = "docs/release-versions.json";
const templatePath = (path) => `docs/release-templates/${basename(path)}.in`;

export const releaseDocumentationInputs = [
  metadataPath,
  ...documents.flatMap((path) => [path, templatePath(path)]),
];

/** Render committed Markdown before checking or packing the versioned package. */
export function releaseDocumentationProjection(version, read) {
  assert.match(version, releaseVersionPattern);
  const metadata = JSON.parse(read(metadataPath));
  assert.deepEqual(Object.keys(metadata), ["previousVersion"]);
  const { previousVersion } = metadata;
  assert.match(previousVersion, releaseVersionPattern);
  assert.notEqual(previousVersion, version, "Release versions must differ");
  const anchorVersion = (value) => value.toLowerCase().replace(/[.+]/gu, "");
  const variables = {
    version,
    previousVersion,
    versionAnchor: `version-${anchorVersion(version)}`,
    migrationAnchor: `from-${anchorVersion(previousVersion)}-to-${anchorVersion(version)}`,
  };
  return new Map(
    documents.map((path) => {
      const template = templatePath(path);
      const source = read(template);
      // Require every destination before the caller can update any file.
      read(path);
      const rendered = source.replace(
        /\{\{release\.([A-Za-z][A-Za-z0-9]*)\}\}/gu,
        (_, name) => {
          assert.ok(
            Object.hasOwn(variables, name),
            `Unknown release variable: ${name}`,
          );
          return variables[name];
        },
      );
      assert.ok(
        !rendered.includes("{{release."),
        `Unresolved release variable in ${template}`,
      );
      return [
        path,
        `<!-- Generated by npm run sync:version from ${template}. -->\n\n${rendered}`,
      ];
    }),
  );
}
